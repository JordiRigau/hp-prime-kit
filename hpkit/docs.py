def parse_result(text):
    """A result as the calculator prints it, as a Python value.

    Lists come as {a,b} and matrices as [[a,b],[c,d]]; both become nested
    lists, because that is what the interpreter returns for either. HP also
    prints a plain vector space-separated -- SIZE of a matrix answers [2 3] --
    so whitespace separates too when there is no comma.

    The calculator writes a negative with U+2212, the mathematical minus
    sign, and an entry is written with the hyphen anybody can type, so the
    two are the same sign here: ppl.minus-sign, measured on the Virtual
    Calculator 2.4, build 2025-09-15."""
    text = text.strip().replace('−', '-')
    if len(text) > 1 and text[0] in '{[' and text[-1] in '}]':
        inner = text[1:-1].replace('] [', '],[')
        out, depth, cur = [], 0, ''
        commas = False
        for c in inner:
            if c in '{[':
                depth += 1
            elif c in ']}':
                depth -= 1
            elif c == ',' and depth == 0:
                commas = True
        sep = ',' if commas else ' '
        for c in inner:
            if c in '{[':
                depth += 1
            elif c in ']}':
                depth -= 1
            if c == sep and depth == 0:
                if cur.strip():
                    out.append(parse_result(cur))
                cur = ''
            else:
                cur += c
        if cur.strip():
            out.append(parse_result(cur))
        return out
    if len(text) > 1 and text[0] == '"' and text[-1] == '"':
        return text[1:-1]
    try:
        return float(text)
    except ValueError:
        return text


def same(got, want):
    """Does what the interpreter answered match a printed result?"""
    if isinstance(got, interp.Matrix):
        got = [list(r) for r in got.rows]
    if isinstance(want, list):
        return (isinstance(got, list) and len(got) == len(want)
                and all(same(g, w) for g, w in zip(got, want)))
    if isinstance(want, float):
        return (isinstance(got, float)
                and abs(got - want) <= TOLERANCE * max(1.0, abs(want)))
    return got == want


def show(v):
    """A value the way the calculator would print it, for messages."""
    if isinstance(v, interp.Matrix):
        v = [list(r) for r in v.rows]
        return '[%s]' % ','.join('[%s]' % ','.join(show(x) for x in r)
                                 for r in v)
    if isinstance(v, list):
        return '{%s}' % ','.join(show(x) for x in v)
    if isinstance(v, float):
        return '%d' % v if v == int(v) and abs(v) < 1e15 else repr(round(v, 11))
    if isinstance(v, str):
        return '"%s"' % v
    return repr(v)


def evaluate(call):
    """-> ('value', v), ('error', message) or ('uncovered', why).

    A call with a `;` is the body of a function; without one it is an
    expression. What the interpreter cannot read is uncovered, never an
    error: an error here means the calculator's kind of refusal."""
    body = call if ';' in call else 'RETURN %s;' % call
    m = interp.Machine()
    try:
        m.load('EXPORT T()\nBEGIN\n  %s\nEND;' % body)
    except Exception as e:
        return 'uncovered', 'the interpreter could not read it: %s' % e
    try:
        return 'value', m.call('T')
    except interp.PPLError as e:
        return 'error', '%s' % e
    except interp.Unsupported as e:
        return 'uncovered', '%s' % e
    except Exception as e:                  # a gap, not a verdict
        return 'uncovered', '%s: %s' % (type(e).__name__, e)


def run_examples(root, entries, covered=None):
    """-> (problems, notes, how many ran) for every entry that says it runs
    on the PC. A different answer is a problem; an example the interpreter
    does not cover is a note, because the interpreter is a subset and says
    so rather than guessing. If `covered` is a set, the (entry, call) of
    every example the interpreter did run is added to it."""
    problems, notes, ran = [], [], 0
    for e in entries:
        if not e.runs:
            continue
        for ex in e.examples:
            if ex.no_value:
                continue        # nothing to compare it with
            kind, got = evaluate(ex.call)
            if kind == 'uncovered':
                notes.append(Problem(root, e.path, ex.line, 'not covered by '
                                     'the interpreter, so not checked: %s'
                                     % got))
                continue
            ran += 1
            if covered is not None:
                covered.add((e.name, ex.call))
            if ex.result is None:
                if kind == 'value':
                    problems.append(Problem(
                        root, e.path, ex.line, 'the interpreter answers %s '
                        'where the entry says error' % show(got)))
                continue
            if kind == 'error':
                problems.append(Problem(
                    root, e.path, ex.line, 'the interpreter raises (%s) where '
                    'the entry says %s' % (got, ex.result)))
            elif not same(got, parse_result(ex.result)):
                problems.append(Problem(
                    root, e.path, ex.line, 'the interpreter answers %s; the '
                    'entry says %s' % (show(got), ex.result)))
    return problems, notes, ran


# --------------------------------------------------------------- generating

def _shift(text):
    """Headings one level down, so an entry sits under its group's title."""
    out, fence = [], False
    for line in text.split('\n'):
        if line.startswith('```'):
            fence = not fence
        if not fence and re.match(r'^#{1,5} ', line):
            line = '#' + line
        out.append(line)
    return '\n'.join(out)


def _rebase(text, src, dst):
    """Relative links written from folder src, rewritten for folder dst."""
    def fix(m):
        label, target = m.group(1), m.group(2)
        if target.startswith(('http://', 'https://', 'mailto:', '#')):
            return m.group(0)
        file_part, sep, anchor = target.partition('#')
        dest = os.path.normpath(os.path.join(src, file_part))
        new = os.path.relpath(dest, dst).replace(os.sep, '/')
        return '[%s](%s%s%s)' % (label, new, sep, anchor)
    return LINK.sub(fix, text)


def _index(root, entries):
    """The index: every documented name on the list, with its entry when it
    has one, and any entry that is not on the list, so nothing is hidden."""
    rows = namelist.read(_list_path(root))[0]
    by_entry = OrderedDict((e.name, e) for e in entries if e.name)
    documented = [r for r in rows if r.documented]
    covered = sum(1 for r in documented if r.name in by_entry)
    lines = ['# Commands', '', GENERATED % '`docs/commands/`', '',
             'Every name PPL has, from [the list of names](names.tsv): what '
             'kind of name it is and where HP files it, and, for the ones '
             'with an entry, what it does and the weakest label among its '
             'examples. How an entry is written: [format.md](../format.md).',
             '']
    if rows:
        rest = [(PLURALS[k], sum(1 for r in rows if r.kind == k))
                for k in PLURALS]
        rest = ['%d %s' % (n, what) for what, n in rest if n]
        lines += ['%d of %d names have an entry so far. The list also holds '
                  '%s, which are not documented one by one.'
                  % (covered, len(documented),
                     ', '.join(rest[:-1]) + ' and ' + rest[-1]
                     if len(rest) > 1 else ''.join(rest)), '']
    lines += ['| Name | Kind | Group | What it does | Weakest evidence |',
              '|---|---|---|---|---|']

    def linked(e, kind):
        return '| [%s](%s/%s.md) | %s | [%s](%s.md) | %s | %s |' % (
            e.name, e.folder, e.stem, kind, e.folder, e.folder, e.summary,
            e.weakest or 'no examples')

    listed = set()
    for r in sorted(documented, key=lambda r: (r.name.lower(), r.name)):
        listed.add(r.name)
        e = by_entry.get(r.name)
        lines.append(linked(e, r.kind) if e else
                     '| `%s` | %s | %s | no entry yet | |'
                     % (r.name, r.kind, r.group or '-'))
    for e in sorted(entries, key=lambda e: e.name or ''):
        if e.name and e.name not in listed:
            lines.append(linked(e, 'not on the list'))
    return '\n'.join(lines) + '\n'


def generated(root, entries, facts=None):
    """-> OrderedDict {path: text}: every page produced from the entries,
    and, for docs/llms.txt, from the facts. Without `facts`, the topic pages
    are read for them."""
    if facts is None:
        facts = load_facts(root)[0]
    commands = os.path.join(root, 'docs', 'commands')
    groups = OrderedDict()
    for e in sorted(entries, key=lambda e: (e.folder, e.name or '')):
        groups.setdefault(e.folder, []).append(e)
    out = OrderedDict()
    for group, members in groups.items():
        lines = ['# %s' % (group[:1].upper() + group[1:]), '',
                 GENERATED % ('`%s/`' % group), '',
                 'Every entry in this group, in full. Each one is written in '
                 'its own file, and that file is where it is edited.', '',
                 '| | |', '|---|---|']
        for e in members:
            lines.append('| [%s](#%s) | %s |' % (e.name, e.name, e.summary))
        lines.append('')
        for e in members:
            body = _rebase(_shift(e.text.strip('\n')),
                           os.path.dirname(e.path), commands)
            lines += ['---', '', '<a name="%s"></a>' % e.name, '', body, '']
        out[os.path.join(commands, group + '.md')] = \
            '\n'.join(lines).rstrip('\n') + '\n'
    out[os.path.join(commands, 'index.md')] = _index(root, entries)
    out[os.path.join(commands, 'groups.md')] = _groups(root, entries)
    out[os.path.join(root, 'docs', LLMS)] = _llms(root, entries, facts)
    tools = _tools_page(root, facts)
    if tools:
        out[tools[0]] = tools[1]
    return out


def _first_sentence(path):
    """-> (the page's title, the first sentence of its first paragraph)."""
    title, para = '', []
    for line in io.open(path, encoding='utf-8').read().split('\n'):
        if not title:
            if line.startswith('# '):
                title = line[2:].strip()
            continue
        if line.strip():
            if line.startswith(('#', '|', '>', '```', '<')):
                if para:
                    break
                continue
            para.append(line.strip())
        elif para:
            break
    text = ' '.join(para)
    m = re.match(r'^(.+?[.!?])(\s|$)', text)
    return title, m.group(1) if m else text


def _llms(root, entries, facts):
    """docs/llms.txt: every fact and every entry on one line each, with its
    link and its one-line summary, for a model to load before anything else.
    The layout is llms.txt's: a title, a quoted summary, paragraphs, then
    sections that are lists of links."""
    rows = namelist.read(_list_path(root))[0]
    documented = [r for r in rows if r.documented]
    names = set(e.name for e in entries if e.name)
    covered = sum(1 for r in documented if r.name in names)
    lines = [
        '# HP Prime PPL reference', '',
        '> One entry per PPL name, and the facts about the HP Prime that no '
        'single command owns. Every claim says how it is known. The reference '
        'calculator is an HP Prime G2 on firmware 2.4.15515.', '',
        'Every claim carries one of four labels, strongest first: `G2`, '
        'measured on a physical HP Prime G2; `emulator`, run on HP\'s Virtual '
        'Calculator, with the answer kept in '
        '[commands/results.tsv](commands/results.tsv); `HP help`, stated in '
        'the calculator\'s built-in help; `unverified`, none of those. How an '
        'entry and a fact are written: [format.md](format.md). Ways apps are '
        'built, as options and not rules: [patterns.md](patterns.md).', '',
        'Whether a name exists is looked up in '
        '[commands/names.tsv](commands/names.tsv): every name in HP\'s help, '
        'command tree and release notes, with its kind and group, the CAS '
        'names included, which get no entry. %d of the %d names that get an '
        'entry have one so far, so a name listed there and missing here is on '
        'HP\'s list but not yet written up. A name that is not on it is '
        'somebody else\'s or nobody\'s, and '
        '[commands/not-hp.tsv](commands/not-hp.tsv) says which.'
        % (covered, len(documented)), '',
        'Cite a fact by its identifier, such as `ppl.local-limit`, and a '
        'command by its name, such as `LEFT`.', '',
        'Generated by `hpprime docs` from the topic pages and the entries: '
        '%d facts and %d entries. Edit those, not this file.'
        % (len(facts), len(entries)), '']

    by_topic = OrderedDict()
    for f in facts:
        stem = os.path.splitext(os.path.basename(f.path))[0]
        by_topic.setdefault(stem, []).append(f)
    order = [t for t in TOPIC_ORDER if t in by_topic] + \
        sorted(t for t in by_topic if t not in TOPIC_ORDER)
    for stem in order:
        page = 'topics/%s.md' % stem
        title, first = _first_sentence(os.path.join(root, 'docs', 'topics',
                                                    stem + '.md'))
        lines += ['## %s' % title, '', '- [%s](%s): %s' % (page, page, first)]
        for f in by_topic[stem]:
            lines.append('- [%s](%s#%s): %s' % (f.ident, page, f.ident,
                                                 f.title))
        lines.append('')

    groups = OrderedDict()
    for e in sorted(entries, key=lambda e: (e.folder, e.name or '')):
        groups.setdefault(e.folder, []).append(e)
    for group, members in groups.items():
        page = 'commands/%s.md' % group
        lines += ['## Commands: %s' % group, '',
                  '- [%s](%s): all %d entr%s of the group on one page'
                  % (page, page, len(members),
                     'y' if len(members) == 1 else 'ies')]
        for e in members:
            lines.append('- [%s](commands/%s/%s.md): %s'
                         % (e.name, e.folder, e.stem, e.summary))
        lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n'


def llms_check(root, entries, facts):
    """docs/llms.txt within its budget, measured on what would be generated,
    so a page that has not been regenerated yet cannot hide the growth."""
    text = _llms(root, entries, facts)
    size = len(text.encode('utf-8'))
    if size > LLMS_BUDGET:
        return [Problem(root, os.path.join(root, 'docs', LLMS), 1,
                        'the index for models would be %d bytes, over its '
                        'budget of %d: it is loaded whole, so every line has '
                        'to earn its place' % (size, LLMS_BUDGET))]
    return []


def _groups(root, entries):
    """Every name on the list that gets an entry, by the group HP files it
    under; a name with an entry links to it."""
    rows = namelist.read(_list_path(root))[0]
    by_entry = OrderedDict((e.name, e) for e in entries if e.name)
    groups = OrderedDict()
    for r in sorted((r for r in rows if r.documented),
                    key=lambda r: (r.group or '~', r.name.lower(), r.name)):
        groups.setdefault(r.group or 'ungrouped', []).append(r)
    lines = ['# Commands by group', '', GENERATED % '`docs/commands/`', '',
             'Every name that gets an entry, under the group HP files it '
             'in. A name that has its entry already links to it. The same '
             'names in alphabetical order, with what each one does: '
             '[index.md](index.md).', '']
    for group, members in groups.items():
        written = [r for r in members if r.name in by_entry]
        cells = []
        for r in members:
            e = by_entry.get(r.name)
            cells.append('[%s](%s/%s.md)' % (e.name, e.folder, e.stem) if e
                         else '`%s`' % r.name)
        lines += ['## %s' % group, '',
                  '%d name%s, %d with an entry.'
                  % (len(members), '' if len(members) == 1 else 's',
                     len(written)), '',
                  ' · '.join(cells), '']
    return '\n'.join(lines).rstrip('\n') + '\n'


# The table in docs/tools.md that says what catches each fact is written
# from CAUGHT in hpkit/lint.py, between these two lines, and edited there.
CAUGHT_START = ('<!-- Written by `hpprime docs` from CAUGHT in hpkit/lint.py, '
                'which is where it is edited. -->')
CAUGHT_END = '<!-- End of the table written by `hpprime docs`. -->'


def _answer(a):
    if a[0] == 'rule':
        return 'lint rule `%s`' % a[1]
    if a[0] == 'write':
        return 'a check to write: %s' % a[1]
    if a[0] == 'command':
        return '`hpprime %s`, held by `%s`' % (a[1], os.path.basename(a[2]))
    if a[0] == 'quiet':
        return 'nothing to catch, and `lint` stays quiet'
    return 'not from a PC: %s' % a[1]


def _caught(facts):
    """The table's rows: every fact, and what catches it."""
    from hpkit import lint
    by_id = dict((f.ident, f) for f in facts)
    rows = ['| Fact | Known from | Caught by |', '|---|---|---|']
    for ident, answers in lint.CAUGHT.items():
        f = by_id.get(ident)
        name = ('[%s](topics/%s#%s)' % (ident, os.path.basename(f.path), ident)
                if f else '`%s`' % ident)
        rows.append('| %s | %s | %s |' % (name, f.label if f else '?',
                                          '; '.join(_answer(a)
                                                    for a in answers)))
    return rows


def _tools_page(root, facts):
    """-> (path, text) of docs/tools.md with its table rewritten, or None
    when the page, or either line that marks the table, is missing."""
    path = os.path.join(root, 'docs', 'tools.md')
    if not os.path.exists(path):
        return None
    text = io.open(path, encoding='utf-8').read()
    if CAUGHT_START not in text or CAUGHT_END not in text:
        return None
    head, rest = text.split(CAUGHT_START, 1)
    tail = rest.split(CAUGHT_END, 1)[1]
    return path, (head + CAUGHT_START + '\n' + '\n'.join(_caught(facts))
                  + '\n' + CAUGHT_END + tail)


def stale(root, entries, facts=None):
    """Generated pages that are missing, out of date, or no longer made."""
    problems = []
    want = generated(root, entries, facts)
    for path, text in want.items():
        if not os.path.exists(path):
            problems.append(Problem(root, path, 1, 'missing: run hpprime '
                                    'docs to generate it'))
        elif io.open(path, encoding='utf-8').read() != text:
            problems.append(Problem(root, path, 1, 'out of date: run hpprime '
                                    'docs to regenerate it'))
    tools = os.path.join(root, 'docs', 'tools.md')
    if os.path.exists(tools) and _key(tools) not in set(_key(p) for p in want):
        problems.append(Problem(root, tools, 1, 'the lines that mark the '
                                'table of what catches each fact are '
                                'missing'))
    commands = os.path.join(root, 'docs', 'commands')
    if os.path.isdir(commands):
        wanted = set(_key(p) for p in want)
        for name in sorted(os.listdir(commands)):
            path = os.path.join(commands, name)
            if name.endswith('.md') and _key(path) not in wanted:
                problems.append(Problem(root, path, 1, 'no folder of entries '
                                        'produces this page: delete it'))
    return problems


def build(root=ROOT, entries=None, facts=None):
    """Write every generated page that differs. -> the paths written."""
    if entries is None:
        entries = load(root)[0]
    written = []
    for path, text in generated(root, entries, facts).items():
        old = (io.open(path, encoding='utf-8').read()
               if os.path.exists(path) else None)
        if old != text:
            with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(text)
            written.append(path)
    return written


def results_check(root, entries, covered=None):
    """The documentation against what the Virtual Calculator answered, in
    docs/commands/results.tsv. An example whose stored answer differs from
    what its entry states is a problem for a person to settle, and so is an
    example labelled emulator with no stored answer.

    So is an example nobody has run. One with no stored answer has to be
    *no value*, which says why there is nothing to run; or labelled G2,
    measured by hand with the evidence in the entry; or among `covered`, the
    (entry, call) pairs the interpreter ran. An example that is none of
    those is a claim nobody has checked."""
    from hpkit import examples
    results = examples.read_results(root)
    covered = covered or set()
    problems = []
    for e in entries:
        for ex in e.examples:
            if ex.no_value:
                continue        # a batch never runs it, so nothing is stored
            r = results.get((e.name, ex.call))
            if r is None:
                if ex.label == 'emulator':
                    problems.append(Problem(
                        root, e.path, ex.line, 'labelled emulator, but '
                        'results.tsv holds no answer for %s' % ex.call))
                elif ex.label != 'G2' and (e.name, ex.call) not in covered:
                    problems.append(Problem(
                        root, e.path, ex.line, 'nobody has run %s: '
                        'results.tsv holds no answer for it, it is not '
                        'measured on a G2, and the interpreter does not run '
                        'it. Run it with hpprime examples, or make it %s and '
                        'say why' % (ex.call, NO_VALUE)))
                continue
            stated = examples.ERROR if ex.result is None else ex.result
            number = None
            if r['type'] == '0':
                try:
                    number = float(r['answer'])
                except ValueError:
                    number = None
            if not examples.agrees(stated, r['answer'], number):
                problems.append(Problem(
                    root, e.path, ex.line, 'the emulator answers %s on %s; '
                    'the entry says %s' % (r['answer'], r['firmware'],
                                           stated)))
    return problems


CODE_SPAN = re.compile(r'`([^`]+)`')
A_NAME = re.compile(r'^([A-Za-z_]\w*)(\(.*\))?;?$')
IN_CAPITALS = re.compile(r'^[A-Z][A-Z0-9_]+$')
LETTER_AND_DIGITS = re.compile(r'^[A-Z][0-9]{1,2}$')
LIBRARY_WORD = re.compile(r'librar', re.I)


def _could_be_a_command(name, call):
    """In capitals, or written as a call: what a reader takes for a command.
    M1 and L12 are the calculator's variables or a program's locals, and d(1)
    and F() are variables or a line of test code."""
    if LETTER_AND_DIGITS.match(name):
        return False
    return bool(IN_CAPITALS.match(name)) or (bool(call) and len(name) >= 3)


def _prose(path):
    """-> the lines of a page, with its code blocks blanked."""
    out, fence = [], False
    for line in io.open(path, encoding='utf-8').read().split('\n'):
        if line.startswith('```'):
            fence = not fence
            out.append('')
        else:
            out.append('' if fence else line)
    return out


def origin_check(root):
    """A name that could be taken for a command and is not on HP's list says
    whose it is, in docs/commands/not-hp.tsv, and a library's name is called
    a library in the paragraph where it appears."""
    path = os.path.join(root, 'docs', 'commands', 'not-hp.tsv')
    rows, bad = namelist.read_others(path)
    problems = [Problem(root, path, n, m) for n, m in bad]
    others = set(r.name for r in rows)
    libraries = set(r.name for r in rows if r.origin == 'library')
    hp = set(r.name.lower() for r in namelist.read(_list_path(root))[0])
    home = _key(os.path.join(root, 'docs', 'topics', 'libraries.md'))
    for page in _layer_files(root):
        for start, text in _paragraphs(_prose(page)):
            for span in CODE_SPAN.finditer(text):
                m = A_NAME.match(span.group(1))
                if not m:
                    continue
                name, call = m.group(1), m.group(2)
                if name in libraries and _key(page) != home \
                        and not LIBRARY_WORD.search(text):
                    problems.append(Problem(
                        root, page, start + 1, '%s is a library\'s: the '
                        'paragraph has to say so' % name))
                if name not in others and name.lower() not in hp \
                        and _could_be_a_command(name, call):
                    problems.append(Problem(
                        root, page, start + 1, '%s is not on HP\'s list: add '
                        'it to docs/commands/not-hp.tsv, which says whose it '
                        'is' % name))
    return problems


def check(root=ROOT):
    """-> (problems, notes): everything wrong with the documentation, and
    the examples the interpreter could not check."""
    entries, facts, problems = load(root)
    covered = set()
    p, notes, _ = run_examples(root, entries, covered)
    problems += cross_check(root, entries, facts)
    problems += list_check(root, entries)
    problems += origin_check(root)
    problems += results_check(root, entries, covered)
    problems += p
    problems += llms_check(root, entries, facts)
    problems += stale(root, entries, facts)
    return problems, notes


# ---------------------------------------------------------------------- cli

USAGE = """hpprime docs [--check]

Hold the documentation to its format, and regenerate the pages made from it.

  (no option)   check the entries, then regenerate docs/commands/<group>.md,
                docs/commands/index.md, docs/commands/groups.md and
                docs/llms.txt from them, the facts and the list of names
  --check       change nothing; exit 1 if anything breaks the format or a
                generated page is out of date

The format is stated in docs/format.md.
"""


def cli(argv):
    if '--help' in argv or '-h' in argv:
        print(USAGE)
        return 0
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(errors='replace')
    entries, facts, problems = load(ROOT)
    if '--check' not in argv:
        if problems:
            print('not regenerating: the entries have problems')
        else:
            for path in build(ROOT, entries):
                print('wrote %s' % _rel(ROOT, path))
    problems, notes = check(ROOT)
    entries, facts, _ = load(ROOT)
    _, _, ran = run_examples(ROOT, entries)
    rows = namelist.read(_list_path(ROOT))[0]
    documented = set(r.name for r in rows if r.documented)
    for n in notes:
        print('%s (note)' % n)
    for p in problems:
        print('%s' % p)
    print('%d entries, %d facts, %d example(s) run through the interpreter; '
          '%d of the %d names on the list have an entry: %d problem(s)'
          % (len(entries), len(facts), ran,
             sum(1 for e in entries if e.name in documented), len(documented),
             len(problems)))
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(cli(sys.argv[1:]))
