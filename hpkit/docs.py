# -*- coding: utf-8 -*-
"""The documentation's format, held as code.

    hpprime docs            check, then regenerate the group pages, the
                            indexes and docs/llms.txt from the entries, the
                            facts and the list of names
    hpprime docs --check    change nothing; exit 1 if anything breaks the
                            format or a generated page is out of date

docs/format.md states the format for a reader. This module holds the pages to
it: the command entries under docs/commands/<group>/, the facts in
docs/topics/, the list of every PPL name in docs/commands/names.tsv, and the
pages generated from them. It also runs the examples of every command the
interpreter implements, because an entry that says it runs on the PC makes a
claim a test can check, and it requires every other example to have been run
somewhere, or to say why it cannot be.

Nothing here judges whether a label is true: that is what the evidence behind
it is for. It judges that every claim carries one.
"""
from __future__ import unicode_literals
import io, os, re, sys
from collections import OrderedDict

from hpkit import interp
from hpkit import names as namelist

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

LABELS = ('G2', 'emulator', 'HP help', 'unverified')     # strongest first
KINDS = ('rule', 'refuted hypothesis')
FIELDS = ('Syntax', 'Group', 'Runs on the PC')
SECTIONS = ('Examples', 'Behaviour', 'Models get wrong', 'Related')
REQUIRED = ('Examples', 'Behaviour')
# The result of an example that has nothing to record: the command's result
# is the screen, or it stops the program, or it is a declaration rather than
# a call. Nothing runs one of these.
NO_VALUE = '*no value*'
TOLERANCE = 2e-4        # HP prints rounded results: MIN(8/3,11/4) -> 2.6667

# The layer built on top of the documentation. The documentation never points
# at it, so that it stands on its own and could be split out.
ABOVE = re.compile(r'(?<![\w-])(kit/|AGENTS\.md|SKILL\.md|docs/ai/|\.planning)')
# Words about how the documentation was built rather than about the Prime: a
# reader who did not follow the project cannot know what phase 7 was, or which
# kit is meant. Each has only that use here, so a pattern can refuse it; the
# words with a legitimate use too (a round trip, the user of a program) are
# kept out by reading instead.
PLANNING = re.compile(r'\b[Pp]hases?\b|\b[Tt](?:his|he) kit\b')

GENERATED = ('<!-- Generated by `hpprime docs` from the entries in %s. '
             'Edit those, not this page. -->')

LINK = re.compile(r'\[([^\]]*)\]\(([^)\s]+)\)')
PARENS = re.compile(r'\(([^()]*)\)')
LABEL_WORD = re.compile(r'(?<!\w)(G2|emulator|HP help|unverified)(?!\w)')
FACT_ID = re.compile(r'^[a-z][a-z0-9]*(\.[a-z0-9][a-z0-9-]*)+$')

# Two names on HP's list can differ only in case and share a group: ROOT the
# app function against Root the app variable, and four more pairs. This
# filesystem cannot hold ROOT.md and Root.md in one folder, so the variable's
# entry keeps its real name in the title and takes this suffix on the file.
# Two more pairs are both variables, the capital Greek sigma against the small
# one in the X and Y statistics, which fold together the same way; there the
# small sigma takes it.
# The suffix is declared once here rather than invented per file, and nothing
# else changes: the index and the group pages already link with the title as
# the text and the file name as the path.
NAME_SUFFIX = '-var'
ANCHOR = re.compile(r'^<a name="([^"]+)"></a>\s*$')
SEPARATOR = re.compile(r'^:?-{3,}:?$')
EVIDENCE = '**Evidence.**'
# What a G2 label needs, in format.md, is what was run and what came back. These
# give a reader nothing to check, and it is how one compile error became a rule.
BARE_EVIDENCE = re.compile(
    r'^\*\*Evidence\.\*\* (Measured|Run|Timed|Seen) on a G2 with firmware [\d.]+\.$'
    r'|recorded in (a|the) table', re.I)

# How the kinds that get no entry of their own are named in the index.
PLURALS = OrderedDict([('cas', 'CAS names'), ('keyword', 'keywords'),
                       ('operator', 'operators')])

# The index a model loads first: every entry and every fact on one line, with
# its link and its one-line summary. It is loaded whole, so it has a budget,
# and the check fails past it rather than letting the file grow unnoticed.
LLMS = 'llms.txt'
LLMS_BUDGET = 100000        # bytes
# The topic pages in the order a program runs into them; a page not named
# here still gets its section, after these.
TOPIC_ORDER = ('ppl', 'interface', 'libraries', 'apps', 'micropython',
               'formats', 'deploy')


class Problem(object):
    """One thing wrong, compiler-shaped: `path:line: message`."""

    def __init__(self, root, path, line, message):
        self.path = _rel(root, path)
        self.line = line
        self.message = message

    def __str__(self):
        return '%s:%d: %s' % (self.path, self.line, self.message)


class Example(object):
    def __init__(self, line, call, result, label, target, no_value=False):
        self.line = line
        self.call = call
        self.result = result        # PPL as displayed, or None
        self.label = label
        self.target = target
        # True when the result is NO_VALUE: there is nothing to compare, so
        # neither the interpreter nor a batch on the emulator runs it, and
        # the entry says in words why there is nothing to record.
        self.no_value = no_value


class Entry(object):
    def __init__(self, path, text):
        self.path = path
        self.text = text
        self.folder = os.path.basename(os.path.dirname(path))
        self.stem = os.path.splitext(os.path.basename(path))[0]
        self.name = None
        self.summary = ''
        self.syntax = []
        self.group = None
        self.runs = False
        self.examples = []

    @property
    def weakest(self):
        """The weakest label among the examples, or None without any."""
        if not self.examples:
            return None
        return max((ex.label for ex in self.examples), key=LABELS.index)


class Fact(object):
    def __init__(self, path, ident, line):
        self.path = path
        self.ident = ident
        self.line = line
        self.title = ''             # the heading that states it
        self.kind = None
        self.label = None


# ------------------------------------------------------------------ reading

def _rel(root, path):
    return os.path.relpath(path, root).replace(os.sep, '/')


def _list_path(root):
    return os.path.join(root, 'docs', 'commands', 'names.tsv')


def _skip_blank(lines, i):
    while i < len(lines) and not lines[i].strip():
        i += 1
    return i


def cells(line):
    """The cells of a Markdown table row. A | inside backticks belongs to
    the cell."""
    line = line.strip()
    if line.startswith('|'):
        line = line[1:]
    if line.endswith('|'):
        line = line[:-1]
    out, cur, code = [], '', False
    for c in line:
        if c == '`':
            code = not code
        if c == '|' and not code:
            out.append(cur.strip())
            cur = ''
        else:
            cur += c
    out.append(cur.strip())
    return out


def _table(lines, i):
    """-> ([(index, cells)], index after it) for the table at lines[i]."""
    rows = []
    while i < len(lines) and lines[i].lstrip().startswith('|'):
        rows.append((i, cells(lines[i])))
        i += 1
    return rows, i


def _has_separator(rows):
    return len(rows) > 1 and all(SEPARATOR.match(c) for c in rows[1][1])


def _paragraphs(lines):
    """-> [(index of its first line, text)], paragraphs split on blanks."""
    out, start, cur = [], None, []
    for i, line in enumerate(list(lines) + ['']):
        if line.strip():
            if start is None:
                start = i
            cur.append(line.strip())
        elif cur:
            out.append((start, ' '.join(cur)))
            start, cur = None, []
    return out


def _label(cell):
    """-> (label, link target or None), or (None, None) if the cell is not
    exactly one label."""
    m = re.match(r'^\[([^\]]+)\]\(([^)\s]+)\)$', cell)
    text, target = (m.group(1), m.group(2)) if m else (cell, None)
    return (text, target) if text in LABELS else (None, None)


def read_entry(root, path):
    """-> (Entry, [Problem]) for one command entry."""
    problems = []

    def bad(line, message):
        problems.append(Problem(root, path, line, message))

    text = io.open(path, encoding='utf-8').read()
    e = Entry(path, text)
    lines = text.split('\n')

    i = _skip_blank(lines, 0)
    if i >= len(lines) or not lines[i].startswith('# '):
        bad(i + 1, 'an entry starts with "# NAME"')
        return e, problems
    e.name = lines[i][2:].strip()
    if e.name != e.stem and e.stem != e.name + NAME_SUFFIX:
        bad(i + 1, 'the title is "%s" but the file is %s.md: they are the '
            'same, or the file adds "%s" where two names differ only in '
            'case' % (e.name, e.stem, NAME_SUFFIX))

    i = _skip_blank(lines, i + 1)
    start = i
    while i < len(lines) and lines[i].strip() and \
            not lines[i].startswith(('|', '#')):
        i += 1
    e.summary = ' '.join(l.strip() for l in lines[start:i])
    if not e.summary:
        bad(start + 1, 'after the title comes one sentence saying what it does')
    elif not e.summary.endswith('.'):
        bad(start + 1, 'the summary is one sentence, ending in a full stop')

    i = _skip_blank(lines, i)
    rows, i = _table(lines, i)
    keys = []
    if not _has_separator(rows):
        bad(i + 1, 'after the summary comes the fields table: Syntax, '
            'Group, Runs on the PC')
    else:
        for n, row in rows[2:]:
            if len(row) != 2:
                bad(n + 1, 'a field row has two cells: the field, its value')
                continue
            key, value = row
            if key not in FIELDS:
                bad(n + 1, 'unknown field "%s": the fields are %s'
                    % (key, ', '.join(FIELDS)))
                continue
            keys.append(key)
            if key == 'Syntax':
                e.syntax.append(value)
            elif key == 'Group':
                e.group = value
                if value != e.folder:
                    bad(n + 1, 'Group is "%s" but the entry lives in %s/'
                        % (value, e.folder))
            elif value not in ('yes', 'no'):
                bad(n + 1, '"Runs on the PC" is yes or no')
            else:
                e.runs = value == 'yes'
        order = [k for j, k in enumerate(keys) if j == 0 or keys[j - 1] != k]
        if order != list(FIELDS):
            bad(rows[0][0] + 1, 'the fields are Syntax (one row per form), '
                'then Group, then Runs on the PC, each of them, in that order')

    sections = []
    for j in range(i, len(lines)):
        if lines[j].startswith('## '):
            sections.append([lines[j][3:].strip(), j, len(lines)])
        elif lines[j].startswith('# '):
            bad(j + 1, 'an entry has one title')
        elif lines[j].strip() and not sections:
            bad(j + 1, 'after the fields come the sections, "## Examples" first')
    for k in range(len(sections) - 1):
        sections[k][2] = sections[k + 1][1]
    names = [s[0] for s in sections]
    for name, j, _ in sections:
        if name not in SECTIONS:
            bad(j + 1, 'unknown section "%s": the sections are %s'
                % (name, ', '.join(SECTIONS)))
    known = [n for n in names if n in SECTIONS]
    if known != sorted(set(known), key=SECTIONS.index):
        bad(sections[0][1] + 1, 'the sections come in this order, once '
            'each: %s' % ', '.join(SECTIONS))
    for name in REQUIRED:
        if name not in names:
            bad(len(lines), 'missing section "## %s"' % name)

    for name, j, end in sections:
        body = lines[j + 1:end]
        if name == 'Examples':
            _examples(e, body, j + 1, bad)
        elif name == 'Behaviour':
            _behaviour(body, j + 1, bad)
        elif name == 'Models get wrong':
            _mistakes(body, j + 1, bad)
    return e, problems


def _examples(e, body, offset, bad):
    k = _skip_blank(body, 0)
    rows, _ = _table(body, k)
    if not _has_separator(rows) or len(rows) < 3 or \
            rows[0][1] != ['Call', 'Result', 'Known from']:
        bad(offset + k + 1, 'Examples is a table, Call | Result | Known '
            'from, with at least one row')
        return
    for idx, row in rows[2:]:
        n = offset + idx + 1
        if len(row) != 3:
            bad(n, 'an example has three cells: the call, the result, and '
                'how the result is known')
            continue
        call, result, known = row
        mc = re.match(r'^`(.+)`$', call)
        if not mc:
            bad(n, 'the call is PPL in backticks')
            continue
        no_value = result == NO_VALUE
        if result == '*error*' or no_value:
            value = None
        else:
            mr = re.match(r'^`(.*)`$', result)
            if not mr:
                bad(n, 'the result is PPL in backticks, *error*, or %s'
                    % NO_VALUE)
                continue
            value = mr.group(1)
        label, target = _label(known)
        if label is None:
            bad(n, 'every example has exactly one label: %s'
                % ', '.join(LABELS))
            continue
        e.examples.append(Example(n, mc.group(1), value, label, target,
                                  no_value))


def _behaviour(body, offset, bad):
    paragraphs = _paragraphs(body)
    if not paragraphs:
        bad(offset, 'Behaviour has at least one paragraph')
    for idx, text in paragraphs:
        if text.startswith(EVIDENCE):
            continue
        if not any(LABEL_WORD.search(inner) for inner in PARENS.findall(text)):
            bad(offset + idx + 1, 'every paragraph in Behaviour says how it '
                'is known, with a label in parentheses: (G2), (HP help)...')


def _mistakes(body, offset, bad):
    k = _skip_blank(body, 0)
    rows, _ = _table(body, k)
    if not _has_separator(rows) or len(rows) < 3 or \
            rows[0][1] != ['They write', 'What happens', 'Seen in']:
        bad(offset + k + 1, 'Models get wrong is a table, They write | What '
            'happens | Seen in, with at least one row')
        return
    for idx, row in rows[2:]:
        if len(row) != 3 or not row[2]:
            bad(offset + idx + 1, 'a mistake models make needs where it '
                'was seen')


def read_topic(root, path):
    """-> ([Fact], [Problem]) for one topic page."""
    problems, facts = [], []

    def bad(line, message):
        problems.append(Problem(root, path, line, message))

    lines = io.open(path, encoding='utf-8').read().split('\n')
    topic = os.path.splitext(os.path.basename(path))[0]
    anchors = [(n, m.group(1)) for n, m in
               ((n, ANCHOR.match(l)) for n, l in enumerate(lines)) if m]
    for a, (n, ident) in enumerate(anchors):
        end = anchors[a + 1][0] if a + 1 < len(anchors) else len(lines)
        block = lines[n:end]
        f = Fact(path, ident, n + 1)
        facts.append(f)
        if not FACT_ID.match(ident) or not ident.startswith(topic + '.'):
            bad(n + 1, 'a fact identifier is the topic, a dot and a slug, '
                'as in %s.something' % topic)
        k = _skip_blank(block, 1)
        if k >= len(block) or not block[k].startswith('## '):
            bad(n + 1, 'the anchor is followed by a "## " heading that '
                'states the fact')
            continue
        f.title = block[k][3:].strip()
        k = _skip_blank(block, k + 1)
        rows, k = _table(block, k)
        fields = OrderedDict()
        for idx, row in rows[2:] if _has_separator(rows) else []:
            if len(row) == 2:
                fields[row[0]] = (n + idx + 1, row[1])
        if list(fields) != ['Identifier', 'Kind', 'Known from']:
            bad(n + 1, 'a fact has the fields Identifier, Kind and Known '
                'from, in that order')
        line, value = fields.get('Identifier', (n + 1, ''))
        if value != '`%s`' % ident:
            bad(line, 'the Identifier field repeats the anchor: `%s`' % ident)
        line, value = fields.get('Kind', (n + 1, ''))
        f.kind = value
        if value not in KINDS:
            bad(line, 'Kind is rule or refuted hypothesis')
        line, value = fields.get('Known from', (n + 1, ''))
        f.label = _label(value)[0]
        if f.label is None:
            bad(line, 'Known from is one label: %s' % ', '.join(LABELS))
        texts = [t for _, t in _paragraphs(block[k:])]
        if not [t for t in texts if not t.startswith(EVIDENCE)]:
            bad(n + 1, 'a fact is stated in a paragraph before its evidence')
        if not [t for t in texts if t.startswith(EVIDENCE)]:
            bad(n + 1, 'a fact ends with a paragraph that begins %s'
                % EVIDENCE)
        if f.label == 'G2' and [t for t in texts if t.startswith(EVIDENCE)
                                and BARE_EVIDENCE.search(t)]:
            bad(n + 1, 'a G2 fact says what was run and what came back: that '
                'it was measured, or written down once, is not evidence. '
                'Measure it, or label it unverified and say what was seen')
    return facts, problems


def load(root=ROOT):
    """-> (entries, facts, problems) for the documentation under root."""
    entries, facts, problems = [], [], []
    commands = os.path.join(root, 'docs', 'commands')
    if os.path.isdir(commands):
        for group in sorted(os.listdir(commands)):
            folder = os.path.join(commands, group)
            if not os.path.isdir(folder):
                continue
            for name in sorted(os.listdir(folder)):
                if name.endswith('.md'):
                    e, p = read_entry(root, os.path.join(folder, name))
                    entries.append(e)
                    problems += p
    facts, p = load_facts(root)
    problems += p
    return entries, facts, problems


def load_facts(root=ROOT):
    """-> (facts, problems) for the topic pages alone."""
    facts, problems = [], []
    topics = os.path.join(root, 'docs', 'topics')
    if os.path.isdir(topics):
        for name in sorted(os.listdir(topics)):
            if name.endswith('.md'):
                f, p = read_topic(root, os.path.join(topics, name))
                facts += f
                problems += p
    return facts, problems


# ----------------------------------------------------------------- checking

def _layer_files(root):
    """Every page of the documentation this module is responsible for: the
    entries, the facts, and the guided path that links to them."""
    out = []
    for sub in ('commands', 'topics', 'start'):
        base = os.path.join(root, 'docs', sub)
        for folder, dirs, files in os.walk(base):
            dirs.sort()
            out += [os.path.join(folder, f) for f in sorted(files)
                    if f.endswith('.md')]
    for name in ('format.md', 'patterns.md', LLMS):
        path = os.path.join(root, 'docs', name)
        if os.path.isfile(path):
            out.append(path)
    return out


def _key(path):
    return os.path.normcase(os.path.abspath(path))


def _inside(path, folder):
    return _key(path).startswith(_key(folder) + os.sep)


def cross_check(root, entries, facts):
    """Names and identifiers unique, links resolving, and nothing pointing at
    the layer built on the documentation."""
    problems = []

    def bad(path, line, message):
        problems.append(Problem(root, path, line, message))

    first = {}
    for e in entries:
        if e.name in first:
            bad(e.path, 1, 'the name %s is already an entry: %s'
                % (e.name, _rel(root, first[e.name])))
        elif e.name:
            first[e.name] = e.path
    seen = {}
    for f in facts:
        if f.ident in seen:
            bad(f.path, f.line, 'the identifier %s is already used at %s:%d'
                % (f.ident, _rel(root, seen[f.ident].path),
                   seen[f.ident].line))
        else:
            seen[f.ident] = f

    known = set((_key(f.path), f.ident) for f in facts)
    topics = os.path.join(root, 'docs', 'topics')
    for path in _layer_files(root):
        fence = False
        for n, line in enumerate(io.open(path, encoding='utf-8')
                                 .read().split('\n'), 1):
            m = ABOVE.search(line)
            if m:
                bad(path, n, 'the documentation must not point at the layer '
                    'built on it: %s' % m.group(1))
            m = PLANNING.search(line)
            if m:
                bad(path, n, 'the documentation speaks of "%s", which is how '
                    'it was built rather than anything about the Prime: say '
                    'what was measured instead' % m.group(0))
            if line.startswith('```'):
                fence = not fence
            if fence:
                continue
            for lm in LINK.finditer(line):
                target = lm.group(2)
                if target.startswith(('http://', 'https://', 'mailto:')):
                    continue
                file_part, _, anchor = target.partition('#')
                dest = (os.path.normpath(os.path.join(os.path.dirname(path),
                                                      file_part))
                        if file_part else path)
                if not os.path.exists(dest):
                    bad(path, n, 'the link %s goes nowhere' % target)
                elif anchor and '.' in anchor and _inside(dest, topics) \
                        and (_key(dest), anchor) not in known:
                    bad(path, n, 'the link %s names no fact' % target)
    return problems


def list_check(root, entries):
    """The list of names well formed, every entry's name on it, and every
    entry in the folder of the group the list gives it."""
    path = _list_path(root)
    rows, bad = namelist.read(path)
    problems = [Problem(root, path, n, m) for n, m in bad]
    by = {}
    for r in rows:
        by.setdefault(r.name, r)
    for e in entries:
        if not e.name or not rows:
            continue
        r = by.get(e.name)
        if r is None:
            problems.append(Problem(root, e.path, 1, '%s is not on the list '
                                    'of names, docs/commands/names.tsv'
                                    % e.name))
        elif r.group != e.folder:
            problems.append(Problem(root, e.path, 1, 'the list files %s under '
                                    '%s, but the entry lives in %s/'
                                    % (e.name, r.group or 'no group',
                                       e.folder)))
    return problems


